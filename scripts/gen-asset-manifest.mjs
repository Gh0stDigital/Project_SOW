// Generates src/config/assetManifest.ts by scanning public/assets.
//
// Why this exists: the asset registry used to be a hand-written list, so
// dropping a PNG into public/assets did nothing until someone remembered to
// add a matching line in TypeScript. Scanning the folder removes the step
// that can be forgotten.
//
// A browser cannot list a directory, so this cannot happen at runtime in a
// built app — the catalogue has to be baked in. What it can do is run by
// itself at every point the project is built or served, which vite.config.ts
// arranges: on dev-server start, on every add or removal while the dev
// server is running, and at the start of a build. Adding art is therefore
// the whole job; there is no command to remember.
//
// Still runnable by hand: `npm run gen:assets`.

import { readdirSync, statSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { artIn, fileTable, frameTable } from './artFiles.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')

/** Watched by the dev server, so it is exported rather than duplicated. */
export const ASSETS_DIR = join(ROOT, 'public', 'assets')
const OUT = join(ROOT, 'src', 'config', 'assetManifest.ts')

/** Categories with no fallback image, by design. */
const NO_DEFAULT_NEEDED = ['ui']

function build() {
  const categories = readdirSync(ASSETS_DIR)
    .filter((d) => statSync(join(ASSETS_DIR, d)).isDirectory())
    .sort()

  const manifest = {}
  const files = {}
  const frames = {}
  const warnings = []
  let total = 0

  for (const category of categories) {
    const art = artIn(join(ASSETS_DIR, category), ['default'])
      // 'default' first: it is every category's fallback, and listing it
      // first keeps it at the head of any picker built from this order.
      .sort((a, b) => (a.slot === 'default' ? -1 : b.slot === 'default' ? 1 : a.slot.localeCompare(b.slot)))
    if (art.length === 0) continue
    const keys = art.map((a) => a.slot)
    // Interface art is read through optionalAsset(), which returns null and
    // lets the caller fall back in its own way — so it has no use for a
    // `default` and should not be nagged about missing one.
    if (!NO_DEFAULT_NEEDED.includes(category) && !keys.includes('default')) {
      warnings.push(`${category}/ has no default image — lookups fall back to its first key.`)
    }
    manifest[category] = keys
    Object.assign(files, fileTable(art, `${category}/`))
    Object.assign(frames, frameTable(art, `${category}/`))
    total += keys.length
  }

  const body = Object.entries(manifest)
    .map(([cat, keys]) => `  ${cat}: [${keys.map((k) => `'${k}'`).join(', ')}],`)
    .join('\n')

  const source = `// Generated by scripts/gen-asset-manifest.mjs — do not edit by hand.
// Rewritten automatically when the dev server starts, when art is added or
// removed while it is running, and at the start of every build.

export const assetManifest = {
${body}
} as const

/**
 * The filename behind each key, keyed "category/key". Art may be any
 * supported format and any capitalisation, so the name is recorded rather
 * than reconstructed from the key.
 */
export const assetFiles: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 2)}

/**
 * Art that is several frames rather than one picture, keyed "category/key".
 *
 * Only slots with more than one frame appear. Everything else reads
 * assetFiles and draws a single image, which is why a slot that gains an
 * animation keeps working in every place that has never heard of one: the
 * first frame is its file.
 */
export const assetFrames: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(frames, null, 2)}
`
  return { manifest, source, total, categories: Object.keys(manifest), warnings }
}

/**
 * Rewrites the manifest from whatever is on disk.
 *
 * Writes only when the content actually changes: the output is a source file
 * the dev server watches, so rewriting it unconditionally would trigger a
 * reload every time this ran.
 */
export function generateAssetManifest() {
  if (!existsSync(ASSETS_DIR)) {
    throw new Error('gen-asset-manifest: no public/assets directory.')
  }
  const { manifest, source, total, categories, warnings } = build()
  const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  const changed = previous !== source
  if (changed) {
    mkdirSync(dirname(OUT), { recursive: true })
    writeFileSync(OUT, source)
  }
  return { changed, total, categories, manifest, warnings }
}

/** Every key in one category, for callers that only care about one. */
export function listCategory(category) {
  return build().manifest[category] ?? []
}

// CLI entry point.
if (process.argv[1] && process.argv[1].endsWith('gen-asset-manifest.mjs')) {
  try {
    const r = generateAssetManifest()
    for (const w of r.warnings) console.warn(`gen-asset-manifest: ${w}`)
    console.log(
      `gen-asset-manifest: ${r.total} images across ${r.categories.length} categories` +
        (r.changed ? '' : ' (unchanged)'),
    )
  } catch (err) {
    console.error(String(err.message ?? err))
    process.exit(1)
  }
}
